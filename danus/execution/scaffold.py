"""Project/worker scaffolding + detached loop launch.

``do_new`` writes the on-disk layout a project needs; ``spawn_loop`` launches a
worker's outer loop detached in its own process group. The loop re-syncs each
worker's managed AGENTS.md / default-skill links and gateway role before every
start, so changing ``ROLE`` never leaves the old harness or tool surface attached.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

from danus import codex

from . import layout as L

# --------------------------------------------------------------------------- #
# atomic file helpers                                                        #
# --------------------------------------------------------------------------- #

def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def symlink(target: Path, link: Path) -> None:
    """Create or update a Danus-managed symlink without replacing real files."""
    if link.is_symlink():
        try:
            if link.resolve() == target.resolve():
                return
        except OSError:
            pass
        link.unlink()
    elif link.exists():
        return
    try:
        os.symlink(target, link)
    except OSError:
        pass


def sync_worker_harness(wl: "L.WorkerLayout", role_name: str) -> None:
    """Attach the smallest standing harness appropriate for ``role_name``.

    Legacy mathematical workers retain ``worker.md`` + the full mathematical
    skill bundle. Scientific roles use ``scientific_worker.md`` and deliberately
    have no default skills in A2-5b/c. Only Danus-managed symlinks are removed; a
    real user-owned skills directory is never deleted.
    """
    symlink(L.harness_contract(role_name), wl.dir / "AGENTS.md")
    skills_link = wl.dir / ".agents" / "skills"
    skills = L.harness_skills_dir(role_name)
    if skills is None:
        if skills_link.is_symlink():
            skills_link.unlink()
        return
    skills_link.parent.mkdir(parents=True, exist_ok=True)
    symlink(skills, skills_link)


def gateway_role(role_name: str) -> str:
    """Map execution ROLE to the gateway role while preserving legacy workers."""
    name = (role_name or "worker").strip().lower()
    return name if name in L.SCIENTIFIC_ROLES else "worker"


# --------------------------------------------------------------------------- #
# codex config template + task placeholder                                   #
# --------------------------------------------------------------------------- #

_CODEX_CONFIG = """\
# Auto-generated by danus (rewritten each time the worker loop starts); do not hand-edit.
[mcp_servers.danus]
command = {python}
args = ["-m", "danus.gateway"]
tool_timeout_sec = 3600

[mcp_servers.danus.env]
DANUS_PROJECT_DIR = {project_dir}
DANUS_AUTHOR = {author}
DANUS_ROLE = {gateway_role}
DANUS_VERIFY_URL = {verify_url}
"""

_TASK_PLACEHOLDER = (
    "# Task\n\n(unassigned — the main agent writes your assignment here via "
    "`danus assign`; you read this file at the start of every round)\n"
)


def _verify_url() -> str:
    return os.environ.get("DANUS_VERIFY_URL", "http://127.0.0.1:8091/verify")


def _default_model() -> str:
    return codex.model()


def write_codex_config(wl: "L.WorkerLayout", role_name: str = "worker") -> None:
    """Write the worker's MCP config pinned to this interpreter and role."""
    atomic_write(wl.codex_config, _CODEX_CONFIG.format(
        python=_toml_str(sys.executable),
        project_dir=_toml_str(str(wl.project_dir)),
        author=_toml_str(wl.name),
        gateway_role=_toml_str(gateway_role(role_name)),
        verify_url=_toml_str(_verify_url()),
    ))


# --------------------------------------------------------------------------- #
# do_new — scaffold a project                                                #
# --------------------------------------------------------------------------- #

def do_new(project: str, roles: str = "high:3,xhigh:4",
           model: Optional[str] = None) -> Dict:
    """Scaffold a project dir + one worker home per effort-roster entry.

    Workers start as the legacy ``ROLE=worker``. Changing the scientific ROLE in
    ``.role`` takes effect on the next loop start.
    """
    pdir = L.project_dir(project)
    if pdir.exists():
        raise SystemExit(f"project already exists: {pdir} (pick another name or remove it)")
    role_pairs = L.parse_roles(roles)
    model = model or _default_model()

    L.workers_dir(project).mkdir(parents=True, exist_ok=True)
    (pdir / "global_memory").mkdir(exist_ok=True)
    (pdir / "fact_graph").mkdir(exist_ok=True)
    atomic_write(
        L.research_charter(project),
        L.research_charter_template().read_text(encoding="utf-8"),
    )

    created: List[str] = []
    for worker, effort in role_pairs:
        wl = L.WorkerLayout(L.worker_dir(project, worker))
        wl.local_memory.mkdir(parents=True, exist_ok=True)
        wl.logs.mkdir(exist_ok=True)
        (wl.dir / ".agents").mkdir(exist_ok=True)
        sync_worker_harness(wl, "worker")

        write_codex_config(wl, "worker")
        atomic_write(wl.task, _TASK_PLACEHOLDER)
        atomic_write(
            wl.role,
            f"MODEL={model}\nREASONING_EFFORT={effort}\nROLE=worker\nDANUS_AUTHOR={worker}\n",
        )
        atomic_write(wl.status,
                     json.dumps({"worker": worker, "state": "created", "round": 0}, indent=2))
        created.append(worker)

    meta = {"name": project, "model": model, "roles": roles, "workers": created}
    atomic_write(pdir / "project.json", json.dumps(meta, ensure_ascii=False, indent=2))
    return {"project_dir": str(pdir), "workers": created}


# --------------------------------------------------------------------------- #
# spawn_loop — detached launch of one worker's outer loop                    #
# --------------------------------------------------------------------------- #

def spawn_loop(wdir: Path) -> int:
    """Launch ``python -m danus.execution <wdir>`` detached in its own group."""
    wl = L.WorkerLayout(wdir)
    wl.logs.mkdir(parents=True, exist_ok=True)
    logf = open(wl.logs / "loop.log", "a", encoding="utf-8")
    try:
        proc = subprocess.Popen(
            [sys.executable, "-m", "danus.execution", str(wdir)],
            stdout=logf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
            start_new_session=True,
        )
    finally:
        logf.close()
    return proc.pid
