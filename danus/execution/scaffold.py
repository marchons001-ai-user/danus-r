"""Project/worker scaffolding + detached loop launch.

``do_new`` writes the on-disk layout a project needs; ``spawn_loop`` launches a
worker's outer loop detached in its own process group. The loop re-syncs each
worker's managed AGENTS.md / default-skill links and gateway role before every
start, so changing ``ROLE`` never leaves the old harness or tool surface attached.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

from danus import codex

from . import layout as L

# --------------------------------------------------------------------------- #
# atomic file helpers                                                        #
# --------------------------------------------------------------------------- #

def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def process_state_start(pid: int) -> tuple[Optional[str], Optional[str]]:
    try:
        fields = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()
        return fields[0], fields[19]
    except (OSError, IndexError):
        return None, None


def write_worker_pid(wl: "L.WorkerLayout", pid: int) -> None:
    _, start = process_state_start(pid)
    text = f"{pid} {start}\n" if start is not None else f"{pid}\n"
    tmp = wl.pid.with_name(f"{wl.pid.name}.{os.getpid()}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, wl.pid)


def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def symlink(target: Path, link: Path) -> None:
    """Create or update a Danus-managed symlink without replacing real files."""
    if link.is_symlink():
        try:
            if link.resolve() == target.resolve():
                return
        except OSError:
            pass
        link.unlink()
    elif link.exists():
        return
    try:
        os.symlink(target, link)
    except OSError:
        pass


def sync_worker_harness(wl: "L.WorkerLayout", role_name: str) -> None:
    """Attach the smallest standing harness appropriate for ``role_name``.

    Legacy mathematical workers retain ``worker.md`` + the full mathematical
    skill bundle. Researcher/Reviewer use ``scientific_worker.md`` with no default
    skills; Experimenter uses the same spine plus its dedicated small skill bundle.
    Only Danus-managed symlinks are removed; a real user-owned skills directory is
    never deleted.
    """
    symlink(L.harness_contract(role_name), wl.dir / "AGENTS.md")
    skills_link = wl.dir / ".agents" / "skills"
    skills = L.harness_skills_dir(role_name)
    if skills is None:
        if skills_link.is_symlink():
            skills_link.unlink()
        return
    skills_link.parent.mkdir(parents=True, exist_ok=True)
    symlink(skills, skills_link)


def sync_worker_workspace(wl: "L.WorkerLayout") -> None:
    """Expose a bound scientific workspace without placing Danus control files in it."""
    workspace = L.scientific_workspace(wl.project_dir)
    if workspace == wl.project_dir.resolve():
        if wl.workspace.is_symlink():
            wl.workspace.unlink()
        return
    if not workspace.is_dir():
        raise ValueError(f"scientific workspace missing: {workspace}")
    if wl.workspace.exists() and not wl.workspace.is_symlink():
        raise ValueError(f"worker workspace path is not Danus-managed: {wl.workspace}")
    symlink(workspace, wl.workspace)


def gateway_role(role_name: str) -> str:
    """Map execution ROLE to the gateway role while preserving legacy workers."""
    name = (role_name or "worker").strip().lower()
    return name if name in L.SCIENTIFIC_ROLES else "worker"


